-- ────────────────────────────────────────────────────────────
-- 2. profiles
-- Linked 1-to-1 to auth.users via Supabase Auth trigger.
-- Stores display information and role — NOT credentials.
-- ────────────────────────────────────────────────────────────
create table if not exists profiles (
  id           uuid primary key references auth.users(id) on delete cascade,
  display_name text        not null,
  email        text        not null,
  phone        text,
  department   text,                          -- e.g. "Computer Science & Engineering"
  year         text,                          -- e.g. "3rd Year"
  student_id   text,                          -- e.g. "CSE-2022-0148"
  role         user_role   not null default 'student',
  avatar_url   text,                          -- Supabase Storage public URL
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

comment on table profiles is
  'Public-facing user profile, linked to Supabase Auth. Does not store passwords.';

-- Auto-update updated_at
create or replace function update_updated_at_column()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger profiles_updated_at
  before update on profiles
  for each row execute procedure update_updated_at_column();


-- ────────────────────────────────────────────────────────────
-- 3. items
-- Core lost/found report records.
-- ────────────────────────────────────────────────────────────
create table if not exists items (
  id             uuid        primary key default gen_random_uuid(),

  -- Human-readable reference tag (e.g. REP-4311 / REC-8802)
  -- Generated by application or DB trigger; must be unique.
  reference_tag  text        not null unique,

  reporter_id    uuid        not null references profiles(id) on delete restrict,

  name           text        not null check (char_length(name) between 2 and 120),
  description    text,
  category       item_category not null default 'Other',
  status         item_status   not null default 'lost',

  -- Free-text location description (e.g. "CS Block • Room 202")
  location       text        not null check (char_length(location) between 2 and 120),

  -- Structured zone for map filtering — derived from location or chosen by user
  zone           campus_zone,

  -- Supabase Storage path (e.g. "item-images/<uuid>/photo.jpg")
  -- NULL when no photo was attached
  image_path     text,

  -- Where the item is physically being held once found
  -- NULL for lost items or when not in custody
  custody_info   text,

  -- Soft resolution: when item is returned/closed
  resolved_at    timestamptz,

  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);

comment on table items is
  'Lost and found item reports submitted by authenticated users.';

comment on column items.image_path is
  'Supabase Storage object path inside the item-images bucket. Construct the public URL via supabase.storage.from("item-images").getPublicUrl(image_path).';

comment on column items.reference_tag is
  'Unique human-readable ID shown in the UI (REP-xxxx for lost, REC-xxxx for found).';

create trigger items_updated_at
  before update on items
  for each row execute procedure update_updated_at_column();

-- Index for common query patterns
create index if not exists items_status_idx      on items(status);
create index if not exists items_reporter_idx    on items(reporter_id);
create index if not exists items_zone_idx        on items(zone);
create index if not exists items_created_at_idx  on items(created_at desc);


-- ────────────────────────────────────────────────────────────
-- 4. claims
-- Ownership claim workflow for found items.
-- ────────────────────────────────────────────────────────────
create table if not exists claims (
  id           uuid        primary key default gen_random_uuid(),

  item_id      uuid        not null references items(id) on delete cascade,
  claimant_id  uuid        not null references profiles(id) on delete restrict,

  status       claim_status not null default 'pending',

  -- Free-text proof-of-ownership note from the claimant
  notes        text        check (char_length(notes) <= 1000),

  -- Set when security/admin reviews the claim
  reviewed_by  uuid        references profiles(id) on delete set null,
  reviewed_at  timestamptz,

  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),

  -- A user may only have one active (non-rejected) claim per item
  unique (item_id, claimant_id)
);

comment on table claims is
  'Ownership claims made against found items. Reviewed by security desk personnel.';

create trigger claims_updated_at
  before update on claims
  for each row execute procedure update_updated_at_column();

create index if not exists claims_item_idx      on claims(item_id);
create index if not exists claims_claimant_idx  on claims(claimant_id);
create index if not exists claims_status_idx    on claims(status);


-- ────────────────────────────────────────────────────────────
-- 5. ROW LEVEL SECURITY
-- ────────────────────────────────────────────────────────────

-- ── 5.0 Role helper function ──────────────────────────────────
--
-- Reads the current user's role directly, bypassing RLS.
-- Required because policies on `profiles` itself cannot safely
-- query `profiles` — doing so causes infinite RLS recursion.
--
-- SECURITY DEFINER: runs as the function owner (elevated context),
-- so it bypasses RLS on profiles when resolving the caller's role.
-- set search_path = public: prevents search_path injection attacks.
-- STABLE: hints to the planner that results will not change within
-- a single statement — safe to cache within a query.
-- EXECUTE revoked from PUBLIC and granted only to authenticated:
-- prevents unauthenticated callers from probing the role table.
-- ──────────────────────────────────────────────────────────────
create or replace function public.get_my_role()
returns user_role
language sql
security definer
stable
set search_path = public
as $$
  select role
  from public.profiles
  where id = auth.uid();
$$;

-- Restrict execution: only authenticated users may call this function.
revoke execute on function public.get_my_role() from public;
grant  execute on function public.get_my_role() to authenticated;


-- ── 5a. profiles ──

alter table profiles enable row level security;

-- Users can read their own profile
create policy "profiles: owner read"
  on profiles for select
  using (auth.uid() = id);

-- Security / admin can read any profile.
-- Uses get_my_role() helper (security definer) to avoid querying
-- profiles from within a profiles RLS policy (which would recurse).
create policy "profiles: security read all"
  on profiles for select
  using ( public.get_my_role() in ('security', 'admin') );

-- Users can insert their own profile row (created by trigger on signup)
create policy "profiles: owner insert"
  on profiles for insert
  with check (auth.uid() = id);

-- Users can update their own profile (except role — role changes need admin)
create policy "profiles: owner update"
  on profiles for update
  using (auth.uid() = id)
  with check (auth.uid() = id);


-- ── 5b. items ──

alter table items enable row level security;

-- All authenticated users can read all items (public browse)
create policy "items: authenticated read"
  on items for select
  using (auth.role() = 'authenticated');

-- Authenticated users can insert their own reports
create policy "items: authenticated insert own"
  on items for insert
  with check (auth.uid() = reporter_id);

-- Reporters can update their own open (non-resolved) items
create policy "items: reporter update own open"
  on items for update
  using (
    auth.uid() = reporter_id
    and resolved_at is null
  )
  with check (auth.uid() = reporter_id);

-- Security / admin can update any item (e.g. mark resolved, update custody_info).
create policy "items: security update any"
  on items for update
  using ( public.get_my_role() in ('security', 'admin') );

-- Reporters can soft-delete (we do not use hard delete — prefer status update)
-- Hard deletes are intentionally not allowed for regular users.


-- ── 5c. claims ──

alter table claims enable row level security;

-- Claimants can read their own claims
create policy "claims: claimant read own"
  on claims for select
  using (auth.uid() = claimant_id);

-- Security / admin can read all claims.
create policy "claims: security read all"
  on claims for select
  using ( public.get_my_role() in ('security', 'admin') );

-- Authenticated users can submit a claim on a found item they did not report
create policy "claims: authenticated insert"
  on claims for insert
  with check (
    auth.uid() = claimant_id
    and exists (
      select 1 from items i
      where i.id = item_id
        and i.status = 'found'
        and i.reporter_id <> auth.uid()
    )
  );

-- Claimants can update notes on their own pending claims only
create policy "claims: claimant update pending"
  on claims for update
  using (auth.uid() = claimant_id and status = 'pending')
  with check (auth.uid() = claimant_id);

-- Security / admin can update any claim (approve / reject / set reviewed_by).
create policy "claims: security update any"
  on claims for update
  using ( public.get_my_role() in ('security', 'admin') );


-- ────────────────────────────────────────────────────────────
-- 6. AUTO-PROVISION PROFILE ON SIGN-UP
-- Supabase Auth fires on auth.users insert.
-- Creates a matching profiles row so the app always has a profile.
-- ────────────────────────────────────────────────────────────
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, display_name, email, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'full_name', split_part(new.email, '@', 1)),
    new.email,
    'student'
  );
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();


